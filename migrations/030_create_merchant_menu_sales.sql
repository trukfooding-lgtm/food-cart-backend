-- เมนูขายดีรายวันของร้าน (ใช้ในหน้า "รายได้" > เมนูขายดี)
CREATE TABLE IF NOT EXISTS merchant_menu_sales (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id INTEGER NOT NULL,
  sale_date   DATE NOT NULL,
  item_name   TEXT NOT NULL,
  quantity    INTEGER NOT NULL DEFAULT 0,
  sales       NUMERIC NOT NULL DEFAULT 0.00,
  updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT merchant_menu_sales_uq UNIQUE (merchant_id, sale_date, item_name)
);

ALTER TABLE merchant_menu_sales ENABLE ROW LEVEL SECURITY;
